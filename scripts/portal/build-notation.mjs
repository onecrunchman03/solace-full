// THE PORTAL — the fold school's notation, a second cipher over the script.
//
//   node scripts/portal/build-notation.mjs
//     → src/portal/notation-ids.ts            (server: mark ↔ script glyph)
//     → client/src/portal/notation-strokes.ts (client: mark → strokes only)
//
// kaal-ith is written in it (PORTAL.md → The hall). The notation covers the
// 26 letters; numbers are written in the common numerals (the primer says
// so, page one). Each mark stands for one letter glyph, so the room is a
// substitution over a substitution: a reader cracks a mark by naming the
// script glyph it stands for, and only then does the script show through.
//
// The marks are drawn on one baseline from six parts, so they read as a
// shorthand and never as letters. Fixed seeds: never rerun this with
// different ones once a server has cracked marks — the mark ids are stored.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "../..");
const ids = readFileSync(join(ROOT, "src/portal/glyph-ids.ts"), "utf8");
const GLYPH_ID = JSON.parse(ids.match(/GLYPH_ID: Record<string, number> = (\{.*\});/)[1]);
const LETTERS = Object.keys(GLYPH_ID).filter((s) => !/^[0-7]$/.test(s));
if (LETTERS.length !== 26) throw new Error(`want 26 letters, have ${LETTERS.length}`);

const BASE = ["p", "M18 96 H82"];
const PARTS = [
  ["p", "M26 96 V36"], // left post
  ["p", "M74 96 V36"], // right post
  ["p", "M26 36 L74 96"], // the fall
  ["c", 50, 24, 9], // the head
  ["p", "M32 64 H68"], // the bar
  ["p", "M34 44 L50 26 L66 44"], // the roof
];

let seed = 0xf01d;
const rand = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 2 ** 32; };
// Every combination of two or three parts, shuffled; the first 26 are the marks.
const combos = [];
for (let m = 1; m < 64; m++) { const n = [...m.toString(2)].filter((b) => b === "1").length; if (n === 2 || n === 3) combos.push(m); }
const shapes = combos.map((m) => [rand(), m]).sort((a, b) => a[0] - b[0]).slice(0, 26).map(([, m]) => [BASE, ...PARTS.filter((_, i) => m & (1 << i))]);
const letters = LETTERS.map((s) => [rand(), s]).sort((a, b) => a[0] - b[0]).map(([, s]) => s);

const server = `// GENERATED by scripts/portal/build-notation.mjs — do not hand-edit.
// The fold school's notation: which script glyph each mark stands for.
// SERVER ONLY: this table is the second cipher's key; never import it in client/.
export const NOTATION_COUNT = 26;
/** Notation marks ride the wire as NOTATION_BASE + mark. */
export const NOTATION_BASE = 100;
/** mark → the script glyph id it stands for */
export const NOTATION_GLYPH: number[] = ${JSON.stringify(letters.map((s) => GLYPH_ID[s]))};
/** script glyph id → its mark */
export const MARK_OF: Record<number, number> = ${JSON.stringify(Object.fromEntries(letters.map((s, i) => [GLYPH_ID[s], i])))};
`;
const client = `// GENERATED by scripts/portal/build-notation.mjs — do not hand-edit.
// The fold school's notation marks, by mark id. Nothing here says which
// letter a mark stands for.
import type { Part } from "./glyph-strokes";
export const NOTATION_BASE = 100;
export const NOTATION_STROKES: Part[][] = ${JSON.stringify(shapes)};
`;
writeFileSync(join(ROOT, "src/portal/notation-ids.ts"), server);
writeFileSync(join(ROOT, "client/src/portal/notation-strokes.ts"), client);
console.log("notation: 26 marks written");
