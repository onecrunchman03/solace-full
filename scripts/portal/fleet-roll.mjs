// THE PORTAL — the Fleet roll (digest 14014).
//
// Oruun prints the crews of the Ninefold Fleet, "and it is long and I have
// not shortened it": 1460 names in their numerals (816 of ours), nine hulls.
// A list of names is not archive prose, so it is generated — seeded, from
// the language's own sounds, so it never changes — like the ring game's move
// list (pinned.md). Hethra Maal stands on the ninth hull, Kesh; the fourth
// hull carries the 130 (88) Oruun had already entered at 14011.
//
//   node scripts/portal/fleet-roll.mjs   → docs/portal/eshai/fleet-roll.md

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "../..");
const TOTAL = 0o1460, FOURTH = 0o130, HULLS = 9;

let seed = 0x5eed14014;
const rand = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 2 ** 32; };
const pick = (a) => a[Math.floor(rand() * a.length)];

// Weighted toward the archive's own names (Oruun Vael, Senneth Ilaar, Tamruk
// Hesh, Kessa Imaa): soft onsets, few clusters, the long vowels now and then.
const ONSET = ["t", "k", "s", "s", "d", "th", "v", "h", "m", "m", "n", "n", "r", "l", "l", "y", "p", "sh", "kh", "w"];
const VOWEL = ["a", "a", "a", "e", "e", "i", "i", "o", "u", "u", "aa", "ee", "ai"];
const SOFT = ["n", "r", "l"];
const END = ["", "", "n", "r", "l", "th", "sh", "k", "s", "m"];
const onset = (first) => (first && rand() < 0.15 ? "" : pick(ONSET));
const syl = (first, coda) => onset(first) + pick(VOWEL) + coda;
const cap = (s) => s[0].toUpperCase() + s.slice(1);
const given = () => cap(syl(true, rand() < 0.3 ? pick(SOFT) : "") + syl(false, pick(END)));
const line = () => cap(rand() < 0.55 ? syl(false, pick(END.filter(Boolean))) : syl(true, "") + syl(false, pick(END.filter(Boolean))));

// Never hand out a name somebody in the hall already wears, nor a common word.
const taken = new Set();
for (const m of readFileSync(join(ROOT, "docs/portal/archive/profiles.md"), "utf8").matchAll(/^\*\*([^*]+)\*\* · keystone/gm)) taken.add(m[1]);
const words = new Set([...readFileSync(join(ROOT, "docs/portal/archive/lexicon.md"), "utf8").matchAll(/^\| ([a-z'-]+) \|/gm)].map((m) => m[1]));

const sizes = Array.from({ length: HULLS }, () => 0);
sizes[3] = FOURTH;
const rest = TOTAL - FOURTH, others = HULLS - 1;
let left = rest;
for (let h = 0, k = 0; h < HULLS; h++) if (h !== 3) { k++; sizes[h] = k === others ? left : Math.floor(rest / others) + (k % 2 ? 1 : -1); left -= sizes[h]; }

const used = new Set(taken);
const roll = sizes.map(() => []);
roll[8].push("Hethra Maal");
used.add("Hethra Maal");
for (let h = 0; h < HULLS; h++) {
  while (roll[h].length < sizes[h]) {
    const n = `${given()} ${line()}`;
    const [g, l] = n.toLowerCase().split(" ");
    if (used.has(n) || words.has(g) || words.has(l)) continue;
    used.add(n);
    roll[h].push(n);
  }
}

const NAMES = ["enna", "daina", "tirna", "kaavna", "pemna", "sulna", "hevna", "10-na", "11-na"];
let out = `# The Fleet roll — digest 14014 (GENERATED by scripts/portal/fleet-roll.mjs; do not hand-edit)\n\n`;
out += `${TOTAL.toString(8)} names, nine hulls, in the order the yards sent them. A name is the same in both scripts.\n`;
roll.forEach((names, h) => {
  out += `\n## Khul ${(h + 1).toString(8)}${h === 8 ? " — Kesh" : ""} (${names.length.toString(8)})\n\n`;
  out += `${NAMES[h]} khul!\n\n`;
  out += names.map((n) => n + "!").join(" ") + "\n";
});
writeFileSync(join(ROOT, "docs/portal/eshai/fleet-roll.md"), out);
console.log(`fleet roll: ${roll.flat().length} names (${TOTAL.toString(8)} in their numerals), hulls ${sizes.join(" ")}`);
