// THE PORTAL — the 34 glyphs, numbered so the wire gives nothing away.
//
//   node scripts/portal/build-glyphs.mjs
//     → src/portal/glyph-ids.ts            (server: sound → id, id → sound)
//     → client/src/portal/glyph-strokes.ts (client: id → strokes, NO sounds)
//
// The shapes are the signed-off sheet (docs/portal/glyphs.html), unchanged.
// The ids are a fixed shuffle, so a reader with the browser's dev tools sees
// shapes and numbers and nothing else: which sound a glyph makes is sent
// only once the community has cracked it. Never rerun this with a different
// seed once a server has unlocked glyphs — the ids are stored.

import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "../..");
const STEM = "M50 16 V84";
const P = (d) => ["p", d], C = (x, y, r) => ["c", x, y, r], D = (x, y) => ["d", x, y];
const DOT = D(50, 101), BAR = P("M30 101 H70"), RING = C(50, 50, 26), ALMOND = P("M16 50 Q50 16 84 50 Q50 84 16 50");
const G = {
  a: [RING], aa: [RING, BAR], e: [ALMOND], ee: [ALMOND, BAR], i: [P("M22 28 Q50 96 78 28")], o: [RING, D(50, 50)], u: [P("M22 78 Q50 8 78 78")], ai: [ALMOND, D(50, 50)],
  p: [P(STEM), P("M50 16 L80 40")], t: [P(STEM), P("M50 16 L20 40")], k: [P(STEM), P("M28 24 L72 40")], s: [P(STEM), P("M50 84 L80 60")],
  d: [P(STEM), P("M50 84 L20 60")], v: [P(STEM), P("M50 50 H76 V70")], n: [P("M34 84 V44 Q52 12 72 38")], h: [P(STEM), P("M28 60 L72 40")],
  m: [P("M26 84 V44 Q50 6 74 44 V84")], r: [P("M50 42 V84"), C(50, 28, 12)], l: [P("M50 16 V58"), C(50, 71, 12)], y: [P(STEM), C(70, 50, 11)],
  w: [P("M14 50 Q32 22 50 50 T86 50")],
};
for (const [soft, base] of [["kh", "k"], ["th", "t"], ["sh", "s"], ["vh", "v"], ["ng", "n"]]) G[soft] = [...G[base], DOT];
for (let n = 0; n < 8; n++) {
  const parts = [P("M18 18 H82")];
  [[4, 30], [2, 50], [1, 70]].forEach(([bit, x]) => { if (n & bit) parts.push(P(`M${x} 18 V66`)); });
  if (n === 0) parts.push(C(50, 50, 13));
  G[String(n)] = parts;
}
const SOUNDS = Object.keys(G); // 26 letters then the digits 0–7
if (SOUNDS.length !== 34) throw new Error(`want 34 glyphs, have ${SOUNDS.length}`);

let seed = 0xe5a1;
const rand = () => { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 2 ** 32; };
const order = SOUNDS.map((s) => [rand(), s]).sort((a, b) => a[0] - b[0]).map((x) => x[1]);
const ID = Object.fromEntries(order.map((s, i) => [s, i]));

const server = `// GENERATED by scripts/portal/build-glyphs.mjs — do not hand-edit.
// The 34 glyphs' ids. SERVER ONLY: this table is the decipherment; it must
// never be imported by anything in client/.
export const GLYPH_COUNT = 34;
/** sound (or digit "0"–"7") → glyph id */
export const GLYPH_ID: Record<string, number> = ${JSON.stringify(ID)};
/** glyph id → sound (or digit) */
export const GLYPH_SOUND: string[] = ${JSON.stringify(order)};
/** the eight numeral glyphs' ids, by value */
export const NUMERAL_IDS: number[] = ${JSON.stringify([..."01234567"].map((d) => ID[d]))};
`;
const client = `// GENERATED by scripts/portal/build-glyphs.mjs — do not hand-edit.
// The 34 glyphs' strokes, by opaque id. No sounds here, on purpose: which
// sound a glyph makes reaches the browser only once it has been cracked.
export type Part = ["p", string] | ["c", number, number, number] | ["d", number, number];
export const STROKES: Part[][] = ${JSON.stringify(order.map((s) => G[s]))};
`;
mkdirSync(join(ROOT, "src/portal"), { recursive: true });
mkdirSync(join(ROOT, "client/src/portal"), { recursive: true });
writeFileSync(join(ROOT, "src/portal/glyph-ids.ts"), server);
writeFileSync(join(ROOT, "client/src/portal/glyph-strokes.ts"), client);
console.log("glyphs: 34 written");
