// THE PROP KIT'S WEIGHT — how much each built model costs the game to draw,
// for the map editor's cost meter (Josh, Oct 2026: "props and triangles per
// area, so a room heavy enough to stutter the game shows up while you're
// building it").
//
//   node scripts/props/cost.mjs      → src/backrooms/props-cost.json
//
// Read from the BUILT files (client/public/assets/propkit/*.gltf), so it
// counts what the game actually loads, after simplification. Per file:
//   [drawCalls, triangles] — one draw call per primitive the scene reaches
//   (a mesh used by two nodes is drawn twice), triangles from each
//   primitive's index count (or its vertex count when it has no indices).
// build.mjs runs this at the end of every kit build, so the two never drift.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const KIT_DIR = path.join(ROOT, "client", "public", "assets", "propkit");
const OUT = path.join(ROOT, "src", "backrooms", "props-cost.json");

/** [draw calls, triangles] for one built glTF's JSON. */
export function gltfCost(j) {
  let calls = 0;
  let tris = 0;
  const seen = new Set();
  const walk = (n) => {
    if (seen.has(n)) return;
    seen.add(n);
    const node = j.nodes?.[n];
    if (!node) return;
    if (node.mesh !== undefined) {
      for (const p of j.meshes[node.mesh].primitives ?? []) {
        calls++;
        const acc = p.indices !== undefined ? j.accessors[p.indices] : j.accessors[p.attributes.POSITION];
        tris += Math.floor((acc?.count ?? 0) / 3);
      }
    }
    for (const c of node.children ?? []) walk(c);
  };
  const scene = j.scenes?.[j.scene ?? 0];
  for (const n of scene?.nodes ?? []) walk(n);
  return [calls, tris];
}

export function writeKitCosts() {
  const files = readdirSync(KIT_DIR).filter((f) => f.endsWith(".gltf")).sort();
  const out = {};
  for (const f of files) out[f.replace(/\.gltf$/, "")] = gltfCost(JSON.parse(readFileSync(path.join(KIT_DIR, f), "utf8")));
  const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(",\n");
  writeFileSync(OUT, `{\n"note": "GENERATED by scripts/props/cost.mjs from the built kit — [drawCalls, triangles] per model file.",\n"files": {\n${body}\n}}\n`);
  return Object.keys(out).length;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`costed ${writeKitCosts()} models → ${path.relative(ROOT, OUT)}`);
}
